// ── Vue-safety ──────────────────────────────────────────────────────────────

/**
 * Escape one run of text that markdown-it will emit as raw HTML.
 *
 * `<` becomes `&lt;` so a description mentioning `<span>` renders as text
 * instead of being compiled as a component; `{{` is escaped so a description
 * containing a mustache cannot become an interpolation. Existing entities are
 * left alone (`&` is not touched), because the inputs are JSDoc prose and
 * TypeScript type strings, neither of which contains entity syntax.
 */
export function escapeVueText(text: string): string {
  return text.replace(/</g, '&lt;').replace(/\{\{/g, '&#123;&#123;')
}

/**
 * The only component tags a generated page may open — TASK-N2-D3.
 *
 * D1 §15 gave D3 two options and forbade the third: *"D3 must add its component
 * tags to an allowlist (or push them through a channel the escaper skips) — and
 * must **not** simply disable the escaper, or `DzBreadcrumb.md` breaks the build
 * again."* This is that allowlist, and it is deliberately a closed set of exact
 * names rather than a pattern: a pattern like `Dz[A-Z]` would also un-escape
 * every `<DzButton …>` a **prop description** happens to contain, which is
 * precisely the class of defect (D1 F-1) the escaper exists to stop. There are
 * 12 descriptions carrying raw HTML in the catalogue today and the escaper is
 * the only thing standing between them and a failed build.
 */
export const ALLOWED_PAGE_COMPONENTS = ['DzPlayground'] as const

/**
 * A line that is entirely one allowlisted component tag, on its own.
 *
 * Anchored at both ends so the tag can only be the whole line — a description
 * that mentions `<DzPlayground>` mid-sentence stays escaped.
 */
// The non-capturing group is redundant only while the allowlist has exactly one
// entry. Removing it would make `^<A|B(?:\s…)?/>$` mean something else entirely
// the moment a second tag is allowed, so it stays and the rule is silenced here.
const ALLOWED_TAG_LINE = new RegExp(
  // eslint-disable-next-line regexp/no-useless-non-capturing-group
  `^<(?:${ALLOWED_PAGE_COMPONENTS.join('|')})(?:\\s[^<>]*)?/>$`,
)

/**
 * True when a line is exactly one allowlisted component tag.
 *
 * Exported so the whole-catalogue "no unescaped markup" assertion in
 * `docs-pages.spec.ts` asks this function rather than carrying its own copy of
 * the allowlist. That assertion failed the moment the playground tag started
 * being emitted (D3-F6): the test's rule and the escaper's rule were the same
 * rule stated twice, and only one of them was updated.
 */
export function isAllowedComponentLine(line: string): boolean {
  return ALLOWED_TAG_LINE.test(line.trim())
}

/**
 * Apply {@link escapeVueText} to a rendered page, skipping fenced code blocks
 * and inline code spans — markdown-it already escapes both, and injecting
 * entities there would make them visible as literal `&lt;`.
 *
 * Fence tracking follows CommonMark: a fence closes on a run of the same
 * character at least as long as the opener, which is the rule
 * `render-llms.ts`'s `fenceFor` relies on when it widens a fence around a
 * snippet that itself contains backticks.
 */
export function escapeForVue(lines: readonly string[]): string[] {
  const out: string[] = []
  let openFence: string | null = null
  let inComment = false
  // Split on real newlines first. `render-llms.ts`'s `fenced()` returns a whole
  // fenced block — opener, body and closer — as ONE array element, so a tracker
  // that only inspected elements would open a fence and never see it close, and
  // would then treat the entire rest of the page as code. That is not
  // hypothetical: it was the first VitePress build failure of this packet
  // (`DzBreadcrumb.md`, "Element is missing end tag" on an unescaped `<span>` in
  // a prop description that sat after the usage snippet).
  for (const line of lines.flatMap(l => l.split('\n'))) {
    const fence = /^(\s*)([`~]{3,})/.exec(line)
    if (openFence !== null) {
      out.push(line)
      if (fence !== null && fence[2]!.startsWith(openFence[0]!) && fence[2]!.length >= openFence.length)
        openFence = null
      continue
    }
    if (fence !== null) {
      openFence = fence[2]!
      out.push(line)
      continue
    }
    // HTML comments pass through unescaped. They are inert in a Vue template,
    // and escaping the `<!--` turns an invisible authoring note into visible
    // page text — which is what the first generated `DzAccordion.md` did.
    if (inComment) {
      out.push(line)
      if (line.includes('-->'))
        inComment = false
      continue
    }
    if (line.trimStart().startsWith('<!--')) {
      out.push(line)
      if (!line.includes('-->'))
        inComment = true
      continue
    }
    // A whole-line, self-closing tag from the closed allowlist passes through
    // unescaped — the ONE channel by which this generator may emit a component
    // (TASK-N2-D3, D1 §15). Everything else, including the same name inside
    // prose, is still escaped by the branch below.
    if (isAllowedComponentLine(line)) {
      out.push(line)
      continue
    }
    // Outside a fence: split on inline-code spans and escape only the gaps.
    const segments = line.split('`')
    out.push(segments.map((seg, i) => (i % 2 === 1 ? seg : escapeVueText(seg))).join('`'))
  }
  return out
}

// ── Small helpers ───────────────────────────────────────────────────────────

/**
 * Drop HTML comment blocks from hand-written prose before it is merged.
 *
 * Each `components/_usage/<Name>.md` opens with an authoring guard-rail — "prose
 * only, do not write a table here". That note is addressed to whoever edits the
 * file, not to a reader of the site, and carrying it onto the page would publish
 * repository instructions as documentation.
 */
export function stripHtmlComments(text: string): string {
  return text.replace(/<!--[\s\S]*?-->/g, '')
}

/** A YAML double-quoted scalar. Front matter is data, so it is quoted, not guessed at. */
export function yamlString(value: string): string {
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`
}

/** Human label for a family key; falls back to the key so an unlabelled family is visible, not hidden. */
export function familyLabel(key: string): string {
  return FAMILY_LABELS[key] ?? key
}

/** Curated family order first, then anything new, alphabetically. */
export function orderedFamilies(artifact: ComponentMetaArtifact): string[] {
  const present = new Set(artifact.components.map(c => c.family))
  return [
    ...FAMILY_ORDER.filter(k => present.has(k)),
    ...[...present].filter(k => !FAMILY_ORDER.includes(k)).sort((a, b) => a.localeCompare(b, 'en')),
  ]
}

/** Public components only, in the same family/name order the whole site uses. */
export function publicComponents(artifact: ComponentMetaArtifact): ComponentMetaRecord[] {
  return groupByFamily(artifact.components.filter(c => c.kind === 'public-component'))
    .flatMap(g => g.components)
}

/** The compound parts belonging to a component, name-sorted. */
export function compoundPartsOf(
  record: ComponentMetaRecord,
  artifact: ComponentMetaArtifact,
): ComponentMetaRecord[] {
  return artifact.components
    .filter(c => c.kind === 'compound-part' && c.parentComponent === record.name)
    .sort((a, b) => a.name.localeCompare(b.name, 'en'))
}

/**
 * Split a rendered component section into `[heading…, metaBullets, rest]`.
 *
 * The meta block is the contiguous run of `- ` bullets that
 * `renderComponentSection` always opens with `- **Install:**`. Splitting on that
 * function's own output rather than re-deriving it keeps the page assembly here
 * and the section shape there, which is the point of reusing the function.
 */
export function splitSection(lines: readonly string[]): {
  head: string[]
  meta: string[]
  rest: string[]
} {
  const start = lines.findIndex(l => l.startsWith('- **Install:**'))
  if (start === -1)
    return { head: [...lines], meta: [], rest: [] }
  let end = start
  while (end < lines.length && lines[end]!.startsWith('- '))
    end += 1
  return {
    head: lines.slice(0, start),
    meta: lines.slice(start, end),
    rest: lines.slice(end),
  }
}

// ── The per-page fidelity block ─────────────────────────────────────────────

/**
 * The measured extraction quality for one component, rendered as a table.
 *
 * Every number is read out of `record.extraction`, which the A2 pipeline
 * publishes per component precisely so a renderer can show it. A row is shown
 * for a member kind with zero members too — "0 events" and "we could not read
 * the events" are different claims, and the notes column says which one applies.
 */
export function renderFidelity(record: ComponentMetaRecord): string[] {
  const x = record.extraction
  const undefinedDefaults = record.props.filter(p => p.default === 'undefined').length
  const fromEmits = record.events.filter(e => e.descriptionSource === 'emits-interface').length
  const modelDerived = record.events.filter(e => e.modelDerived).length

  /**
   * True when the component declares an API in source and the extractor
   * recovered none of it.
   *
   * Every "0" in the table below then means **unknown**, not **none**, and the
   * Notes column has to say so. Writing "the component emits nothing" for
   * `DzAccordion` would be the exact failure this whole page argues against:
   * a zero that reads as a measurement when it is an absence of one.
   */
  const gap = record.typesSource !== undefined
    && record.props.length === 0 && record.events.length === 0 && record.slots.length === 0
  const unknown = 'unknown — the extractor recovered nothing for this component (see below)'

  const rows: string[][] = [
    ['Props', String(x.props), String(x.propsWithDescription), gap
      ? unknown
      : undefinedDefaults === 0
        ? `${x.propsWithDeclaredDefault} declare a default`
        : `${x.propsWithDeclaredDefault} declare a default, of which ${undefinedDefaults} declare \`undefined\` (ADR-20 provider supplies the value)`],
    ['Events', String(x.events), String(x.eventsWithDescription), gap
      ? unknown
      : x.events === 0
        ? 'the component emits nothing'
        : `${fromEmits} recovered from the \`Dz*Emits\` interface · ${modelDerived} synthesised by \`defineModel\``],
    ['Slots', String(x.slots), String(x.slotsWithDescription), gap
      ? unknown
      : x.slots === 0
        ? 'the component declares no slots'
        : `${x.slotsWithPayload} carry slot props`],
    ['Exposed on `ref`', String(x.exposed), String(x.exposedWithDescription), gap
      ? unknown
      : x.exposed === 0
        ? 'nothing is exposed on the template ref'
        : 'no description exists in source for any exposed member, catalog-wide'],
  ]

  const lines = [
    '## Extraction fidelity',
    '',
    'Published rather than assumed. These are this component\'s own numbers, measured by the',
    'extraction that produced the tables above.',
    '',
    '| Member kind | Extracted | With a description | Notes |',
    '| --- | --- | --- | --- |',
    ...rows.map(r => `| ${r.join(' | ')} |`),
    '',
  ]

  if (x.unresolvedTypes.length > 0) {
    lines.push(
      `**${x.unresolvedTypes.length} member type(s) could not be resolved** and are printed as the`,
      `extractor left them: ${x.unresolvedTypes.map(t => `\`${t}\``).join(', ')}.`,
      '',
    )
  }

  if (record.props.length === 0 && record.events.length === 0 && record.slots.length === 0) {
    lines.push(
      record.typesSource === undefined
        ? '::: tip Nothing to extract\nThis component declares no API in source, so the absence above is the whole truth.\n:::'
        : '::: danger Extraction gap — do not read the absence above as an empty API\n'
          + `\`${record.name}\` declares its API in \`${record.typesSource}\`, yet the extractor recovered `
          + 'no props, events or slots from it. **This page cannot tell you what the component accepts.** '
          + 'Read the types file. This is tracked as a downward-only ratchet so a second component '
          + 'cannot enter this state unnoticed.\n:::',
      '',
    )
  }

  if (record.stories.primary === undefined && record.kind === 'public-component') {
    lines.push(
      '::: warning No published example\n'
      + 'No Storybook story exists for this component, so no usage snippet is shown. This site never '
      + 'synthesises example markup.\n:::',
      '',
    )
  }

  return lines
}

