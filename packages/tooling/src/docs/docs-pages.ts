/**
 * The docs site's page renderer (TASK-N2-D1).
 *
 * Pure functions: artifact in, markdown out. No filesystem, no `.vue`, no
 * `.types.ts`, no TypeScript program — constraint **B9** makes
 * `packages/core/docs/component-meta.json` the single component-API extraction
 * in this repository, and a docs app that parsed a component source would be
 * the second one.
 *
 * ## This is NOT a second renderer
 *
 * The body of every component page is
 * {@link renderComponentSection | `renderComponentSection`} from
 * `../llms/render-llms.ts` — literally the function `llms-full.txt` is built
 * from, called with `{ level: 1, memberHeadingLevel: 2 }`. The N2-A3 handoff
 * §14 handed that seam forward and asked for exactly this: a `level` parameter
 * on the existing function rather than a copy of it, "because it keeps the
 * shape in one place". So the three rules an API renderer must not get wrong —
 * declared-vs-effective defaults, `descriptionSource`, verbatim-or-absent
 * examples — are implemented once, and this file cannot drift from
 * `llms-full.txt` because it *is* `llms-full.txt`'s renderer.
 *
 * What this module adds is everything a *page* needs that a section does not:
 * front matter, family/kind provenance, the "how to read this page" contract,
 * the merge point for hand-written usage prose, the compound parts nested under
 * their parent, and a per-page extraction-fidelity block.
 *
 * ## Why the fidelity block exists
 *
 * README §3 `<evidence_rules>`: *stale/unrun cells stay visible*. A prop table
 * that renders 12 rows and says nothing else invites the reader to conclude the
 * component is fully documented. Publishing the per-component measurements
 * beside the table — how many descriptions exist, how many defaults are
 * declared `undefined`, where event prose came from, that no `defineExpose`
 * member anywhere in the catalog has a description — is the same argument the
 * N1 lane makes about evidence generally, applied to documentation.
 *
 * ## Vue-safety
 *
 * VitePress compiles markdown to a Vue SFC, so a bare `<span>` in a prop
 * description (53 members in the catalog carry angle brackets) would be parsed
 * as a component and can break the build. {@link escapeForVue} escapes `<` and
 * `{{` outside fenced blocks and outside inline code spans, where markdown-it
 * has not already escaped them.
 *
 * @module @dzup-ui/tooling/docs/docs-pages
 */

