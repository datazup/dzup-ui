// ── The playground section (TASK-N2-D3) ─────────────────────────────────────

/**
 * The *Playground* section of a component page.
 *
 * Two shapes, and only two. Either the component has a story whose static
 * template stands alone outside Storybook — in which case the page emits the
 * one allowlisted tag and the seed is looked up at runtime from
 * `public/playground/seeds.json` — or it has none, in which case the page says
 * so in a sentence and emits **nothing**.
 *
 * There is no third shape. The task says twice that a playground must run real
 * story code and never synthesised markup, and **15 of 144** public components
 * have no story that qualifies (D3-F1). Those 15 get the honest absence, in the
 * same register D1 uses for `DzThemeProvider`'s missing example and D2 uses for
 * the `unrun` capability cells.
 *
 * **The absence states the MEASURED reason**, carried here as a `SeedRefusal`
 * from the one place that decides. It did not always: the first implementation
 * of this section composed a plausible sentence at render time, and on three
 * pages that sentence was false (D3-F5). A reason a page infers is a metric a
 * page hand-types.
 *
 * The seed is NOT inlined into the markdown, deliberately. Every byte written
 * here lands in the page, in the 20.67 MB static build **and in the offline
 * search index** — D2's F-10 measured that index doubling to 1.54 MB because
 * evidence headings are indexed, and 144 SFC seeds would be the next such
 * doubling for content no reader searches for.
 */
/**
 * The one sentence a page prints in place of a playground.
 *
 * Exhaustive over `SeedRefusalReason` with no `default:` branch, so a new
 * refusal reason is a compile error here rather than a silently generic
 * sentence — which is how the three false sentences got published.
 */
export function refusalSentence(refusal: SeedRefusal): string {
  const file = refusal.file === undefined ? 'its stories file' : `\`${refusal.file}\``
  switch (refusal.reason) {
    case 'no-stories-file':
      return 'It has no stories file, so there is no real example to run — and this page will not '
        + 'invent one.'
    case 'no-runnable-story':
      return `Every story in ${file} either has a computed template or binds Storybook's \`args\`, `
        + 'neither of which can be mounted outside Storybook. A playground here would have to be '
        + 'written by hand, and a hand-written example is not evidence of anything.'
    case 'no-component-tag':
      return `The runnable story in ${file} opens no component tag, so a sandbox seeded from it `
        + 'would render an empty box rather than this component.'
    case 'unexported-tags': {
      const tags = refusal.tags ?? []
      const named = tags.map(t => `\`<${t}>\``)
      const list = named.length < 2 ? named.join('') : `${named.slice(0, -1).join(', ')} and ${named.at(-1)}`
      const one = named.length === 1
      return `The runnable story in ${file} opens ${list}, which \`@dzup-ui/core\` does not `
        + `export — ${one ? 'it is' : 'they are'} defined inside the story file itself. A sandbox `
        + `cannot import ${one ? 'it' : 'them'}, and substituting something else would be inventing `
        + 'the example.'
    }
  }
}

export function renderPlayground(
  record: ComponentMetaRecord,
  hasSeed?: boolean,
  refusal?: SeedRefusal,
): string[] {
  if (record.kind !== 'public-component')
    return []

  const runnable = record.stories?.runnable
  const lines: string[] = ['## Playground', '']

  // `hasSeed` is the authority when the caller has it, because
  // `playground-seeds.ts` applies two rules this renderer cannot see (a template
  // that opens no component tag; a tag the library does not export). A page must
  // never promise a playground the site has no seed for, so the two are compared
  // by `validate:docs-pages` as well as wired together here.
  const seeded = hasSeed ?? (runnable?.template !== undefined)
  if (!seeded || runnable === undefined || runnable.template === undefined) {
    // The fallback exists only for callers that pass neither (unit tests of the
    // D1 shape). Generated pages always carry the measured refusal.
    const measured: SeedRefusal = refusal
      ?? (record.stories?.file === undefined
        ? { reason: 'no-stories-file' }
        : { reason: 'no-runnable-story', file: record.stories.file })
    lines.push(
      'No editable playground is published for this component.',
      '',
      refusalSentence(measured),
      '',
    )
    return lines
  }

  const label = runnable.name ?? runnable.id
  lines.push(
    `Editable, running the **${label}** story from \`${record.stories?.file ?? 'the stories file'}\` `
    + `(lines ${runnable.lines[0]}–${runnable.lines[1]}) **verbatim**. `
    + 'Edits run in a sandbox; nothing here is saved.',
    '',
    `<DzPlayground component="${record.name}" />`,
    '',
  )
  return lines
}

export interface ComponentPageInput {
  record: ComponentMetaRecord
  artifact: ComponentMetaArtifact
  /** Hand-written prose from `components/_usage/<Name>.md`, already read. Merged verbatim. */
  usageProse?: string
  /**
   * The generated evidence artifacts (TASK-N2-D2). When present the page gains
   * its *Accessibility and evidence* section; when absent the page is exactly
   * what D1 published, which keeps every D1 unit test meaningful.
   */
  evidence?: EvidenceSources
  /**
   * Public components the seeds artifact actually carries a playground for
   * (TASK-N2-D3). Omitted in unit tests, where the record's own
   * `stories.runnable` is the answer.
   */
  playgroundSeeded?: ReadonlySet<string>
  /**
   * The measured reason each seed-less public component has no playground
   * (TASK-N2-D3), keyed by component name. Omitted in unit tests.
   */
  playgroundRefusals?: ReadonlyMap<string, SeedRefusal>
}

/**
 * One component's page: front matter, the reused `llms-full.txt` section at
 * page level, the contract note, hand-written prose, nested compound parts and
 * the fidelity block.
 */
export function renderComponentPage(input: ComponentPageInput): string {
  const { record, artifact, usageProse, evidence, playgroundSeeded, playgroundRefusals } = input
  const section = renderComponentSection(record, artifact, { level: 1, memberHeadingLevel: 2 })
  const { head, meta, rest } = splitSection(section)
  const parts = compoundPartsOf(record, artifact)

  const provenance = [
    `- **Family:** ${familyLabel(record.family)}`,
    `- **Source:** \`${record.source}\`${record.typesSource === undefined ? '' : ` · types \`${record.typesSource}\``}`,
  ]
  if (parts.length > 0)
    provenance.push(`- **Compound parts:** ${parts.map(p => `\`${p.name}\``).join(', ')}`)

  const body: string[] = [
    ...head,
    ...provenance,
    ...meta,
    '',
    ...HOW_TO_READ,
    '',
    ...rest,
    // TASK-N2-D3. Directly under the static usage snippet, because the two are
    // the same story file read two ways: the snippet is what you paste, the
    // playground is what you press.
    ...renderPlayground(
      record,
      playgroundSeeded === undefined ? undefined : playgroundSeeded.has(record.name),
      playgroundRefusals?.get(record.name),
    ),
  ]

  const prose = stripHtmlComments(usageProse ?? '').trim()
  if (prose !== '') {
    body.push(
      '## Usage notes',
      '',
      '<!-- hand-written prose, merged from components/_usage/'
      + `${record.name}.md — the only non-generated content on this page -->`,
      '',
      prose,
      '',
    )
  }

  if (parts.length > 0) {
    body.push(
      '## Compound parts',
      '',
      `\`${record.name}\` is used with ${parts.length} sub-part${parts.length === 1 ? '' : 's'}, `
      + 'documented here rather than on pages of their own because they are not usable outside it.',
      '',
    )
    for (const part of parts)
      body.push(...renderComponentSection(part, artifact, { level: 3, memberHeadingLevel: 4 }))
  }

  body.push(...renderFidelity(record))

  // D1's §14 seam, taken exactly as offered: one call, after `renderFidelity`,
  // inside `renderComponentPage` — so the freshness gate, the fingerprint, the
  // orphan clause and `validate:docs-pages` all cover the evidence section
  // without a second generator or a second app.
  if (evidence !== undefined)
    body.push(...renderEvidence(record, evidence))

  const description = record.description === ''
    ? `${record.name} — API reference generated from source.`
    : record.description.replace(/\s+/g, ' ').trim()

  const frontMatter = [
    '---',
    `title: ${yamlString(record.name)}`,
    `description: ${yamlString(description)}`,
    'outline: [2, 3]',
    '---',
    '',
    GENERATED_BANNER,
    '',
  ]

  // Deliberately NOT collapsing blank runs: the usage snippet is a verbatim
  // slice of a story file and re-flowing it would stop being verbatim.
  return `${[...frontMatter, ...escapeForVue(body)].join('\n').trimEnd()}\n`
}

// ── The components index ────────────────────────────────────────────────────

/**
 * `components/index.md` — every public component, grouped by family, with its
 * one-line description. This is what makes a family name searchable: the local
 * search index is built from page text, so "overlays" has to appear as text
 * somewhere it can match.
 */
export function renderComponentsIndex(artifact: ComponentMetaArtifact): string {
  const groups = groupByFamily(artifact.components.filter(c => c.kind === 'public-component'))
  const t = artifact.totals
  const lines: string[] = [
    '---',
    'title: "Components"',
    'description: "Every public dzup-ui component, grouped by family, with generated API tables."',
    'outline: [2, 2]',
    '---',
    '',
    GENERATED_BANNER,
    '',
    '# Components',
    '',
    `${t.publicComponents} public components across ${groups.length} families, plus ${t.compoundParts} `
    + 'compound sub-parts documented on their parent\'s page. Every table on every component page is '
    + `extracted from source by \`${artifact.extractor}\`; nothing here is hand-typed.`,
    '',
  ]
  for (const group of groups) {
    lines.push(`## ${group.label}`, '')
    for (const c of group.components) {
      const desc = c.description === '' ? '' : ` — ${c.description.replace(/\s+/g, ' ').trim()}`
      lines.push(`- [${c.name}](./${c.name}.md)${desc}`)
    }
    lines.push('')
  }
  return `${escapeForVue(lines).join('\n').trimEnd()}\n`
}

// ── Navigation data consumed by .vitepress/config.ts ────────────────────────

/** One sidebar group — a family and its public components. */
export interface DocsNavGroup {
  /** Family key, e.g. `overlays`. */
  key: string
  /** Human label, e.g. `Overlays`. */
  text: string
  items: Array<{ text: string, link: string }>
}

/**
 * The data `.vitepress/config.ts` builds its sidebar from, plus the fingerprint
 * the config asserts against the artifact on disk.
 *
 * The fingerprint is a *second* staleness axis and catches a different failure
 * from the freshness gate: the artifact can be regenerated after the pages
 * were, leaving 144 correct-looking pages describing the previous extraction.
 * `vitepress build` then fails on its own, without needing the 20-second
 * re-extraction.
 */
export interface DocsNav {
  generator: string
  /** SHA-256 of the artifact these pages were rendered from. */
  artifactSha256: string
  schemaVersion: string
  extractor: string
  sourceCommit: string
  publicComponents: number
  compoundParts: number
  groups: DocsNavGroup[]
  /**
   * SHA-256 of every evidence artifact the pages were rendered from, by
   * repo-relative path (TASK-N2-D2).
   *
   * The same second staleness axis, widened. D1's fingerprint covered one
   * artifact because one artifact produced every page; the evidence layer reads
   * several, and any of them moving after a render leaves the site publishing a
   * measurement that has since changed. An absent artifact is recorded as
   * absent, so its *appearance* is a change too.
   */
  evidenceSha256: Record<string, string>
  /** The evidence-section counts the site header shows. */
  evidence?: {
    cells: number
    unrunCells: number
    atCells: number
    atExecuted: number
  }
}

/** Build the navigation payload. Pure over the artifact plus the hashes of its inputs. */
export function buildNav(
  artifact: ComponentMetaArtifact,
  artifactSha256: string,
  evidence?: EvidenceSources,
): DocsNav {
  const groups = groupByFamily(artifact.components.filter(c => c.kind === 'public-component'))
  const cells = evidence?.capability.rows.flatMap(r => r.cells) ?? []
  return {
    generator: 'yarn generate:docs-pages (TASK-N2-D1, evidence layer TASK-N2-D2)',
    artifactSha256,
    schemaVersion: artifact.schemaVersion,
    extractor: artifact.extractor,
    sourceCommit: artifact.sourceCommit,
    publicComponents: artifact.totals.publicComponents,
    compoundParts: artifact.totals.compoundParts,
    groups: groups.map(g => ({
      key: g.key,
      text: g.label,
      items: g.components.map(c => ({ text: c.name, link: `/${COMPONENTS_DIR}/${c.name}` })),
    })),
    evidenceSha256: evidence?.fingerprints ?? {},
    ...(evidence === undefined
      ? {}
      : {
          evidence: {
            cells: cells.length,
            unrunCells: cells.filter(c => c.state === 'unrun').length,
            atCells: evidence.atMatrix.entries.reduce((n, e) => n + e.rows.length, 0),
            atExecuted: evidence.atMatrix.entries
              .reduce((n, e) => n + e.rows.filter(r => r.result !== 'unrun').length, 0),
          },
        }),
  }
}
