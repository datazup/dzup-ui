/** `/evidence/at-matrix` — every declared AT/browser pairing, and what has run. */
export function renderAtMatrixPage(ev: EvidenceSources): string {
  const t = computeTotals(ev)
  const byTier = new Map<string, number>()
  for (const e of ev.atMatrix.entries)
    byTier.set(e.tier, (byTier.get(e.tier) ?? 0) + 1)

  const lines: string[] = [
    ...pageHead({
      title: 'Assistive-technology matrix',
      description:
        'Every screen-reader and browser pairing each dzup-ui component owes, and the honest count of how many have been executed.',
    }, '[2, 2]'),
    '# Assistive-technology matrix',
    '',
    `**${t.atExecuted} of ${t.atCells} cells executed.**`,
    '',
    t.atExecuted === 0
      ? 'That is the whole result. No component in this library has been driven with a screen reader '
      + 'and had the result recorded. Everything below describes what is owed, not what is known.'
      : 'The unexecuted cells below are listed with the same weight as the executed ones.',
    '',
    ...ACCESSIBILITY_STATEMENT.blocks.at!,
    '',
    ...ACCESSIBILITY_STATEMENT.blocks.cellDefect!,
    '',
    '## The declared pairings',
    '',
    `A cell is one component times one pairing. ${ev.atMatrix.pairs.length} pairings are declared, and `
    + 'each is here because it can expose something the others cannot.',
    '',
    '| Pairing | Assistive technology | Browser | Platform | What only it exposes |',
    '| --- | --- | --- | --- | --- |',
    ...ev.atMatrix.pairs.map(
      p => `| \`${p.id}\` | ${cell(p.at)} | ${cell(p.browser)} | ${cell(p.platform)} | ${cell(p.purpose)} |`,
    ),
    '',
    '## Which components owe a run',
    '',
    `${t.atComponents} components carry a row: `
    + `${[...byTier.entries()].sort().map(([tier, n]) => `${n} at Tier ${tier}`).join(', ')}. `
    + 'The lowest risk tier is excluded from the matrix entirely.',
    '',
    '::: warning The matrix declares no tier-differentiated obligation',
    'Every component in it owes every pairing, whatever its tier — the obligation is inherited from the',
    'lowest tier that carries it and is never widened. Whether the highest-risk components should owe',
    'more than the lowest is an open owner decision, recorded rather than quietly answered.',
    ':::',
    '',
    '| Component | Tier | APG pattern | Tasks per pairing | Executed | Executable script |',
    '| --- | --- | --- | --- | --- | --- |',
  ]
  for (const e of [...ev.atMatrix.entries].sort((a, b) => a.component.localeCompare(b.component, 'en'))) {
    const executed = e.rows.filter(r => r.result !== 'unrun').length
    const script = ev.atScripts[e.component]
    lines.push(
      `| [${e.component}](/components/${e.component}#assistive-technology) | \`${e.tier}\` `
      + `| \`${e.pattern}\` | ${e.tasks.length} | `
      + `${executed === 0 ? `**0 of ${e.rows.length}**` : `${executed} of ${e.rows.length}`} `
      + `| ${script === undefined ? '—' : `\`${script}\``} |`,
    )
  }
  const scripted = ev.atMatrix.entries.filter(e => ev.atScripts[e.component] !== undefined)
  lines.push(
    '',
    `**${scripted.length} of ${ev.atMatrix.entries.length} components have an executable script.** A `
    + 'script names the story to open, the keys to press and the announcement each step must produce; '
    + 'its expectations are derived from the pattern rather than from what the component currently '
    + 'does, so that a real defect is recorded as a failure instead of being written into the '
    + 'expectation. The remainder owe cells with no script yet.',
    '',
    '## What a recorded run will look like',
    '',
    'The record is append-only: a generator can rewrite the header but never a result row, and a row',
    'that says anything other than `unrun` must carry the tester, the date, the assistive-technology',
    'and browser versions, and the commit the component was at. A result with nothing behind it is',
    'worse than `unrun`, because `unrun` is true.',
    '',
    ...provenance(ev, ['e2e/at-matrix/index.json', 'packages/core/docs/capability-matrix.json']),
  )
  return `${escapeForVue(lines).join('\n').trimEnd()}\n`
}

