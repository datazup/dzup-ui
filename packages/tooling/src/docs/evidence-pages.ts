/**
 * The standalone evidence pages under `/evidence/` (TASK-N2-D2).
 *
 * Six generated pages: the hub, the capability matrix, the assistive-technology
 * matrix, the accessibility conformance statement, the browser-support
 * statement, and the styling-posture statement.
 *
 * ## Generated pages, including the two "statements"
 *
 * The task calls the styling and browser statements *authored prose (they are
 * policy, not data)* — and requires that *every factual claim in them (engine
 * versions, layer names, pilot counts) is generated or omitted*. Those two
 * requirements pull in opposite directions if the page is a hand-written
 * markdown file, because nothing then stops a number being typed into it.
 *
 * So the prose lives in `statements.ts` (hand-written, gated to contain no
 * metric at all) and the *page* is generated around it. That puts both
 * statements inside `validate:docs-pages`: hand-editing one fails the gate, and
 * a number can only reach the page by being read out of an artifact here.
 *
 * ## Everything under `apps/docs/evidence/` is generated
 *
 * `apps/docs/guide/` is hand-written, `apps/docs/components/` and
 * `apps/docs/evidence/` are generated, and the orphan clause enforces the
 * boundary in both generated directories.
 *
 * @module @dzup-ui/tooling/docs/evidence-pages
 */

