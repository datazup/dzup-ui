/** One row of the SC 2.5.7 audit, rendered for the conformance page. */
function auditRow(s: WcagSurface): string {
  return `| [${s.component}](/components/${s.component}#accessibility-and-evidence) `
    + `| ${cell(s.operation)} | ${cell(s.keyboardAlternative)} `
    + `| ${s.singlePointerNoDrag === null ? '**none**' : cell(s.singlePointerNoDrag)} `
    + `| ${s.state === 'gap' ? '**gap**' : 'met'} |`
}

/** `/evidence/accessibility` — the conformance statement. */
export function renderAccessibilityPage(ev: EvidenceSources): string {
  const t = computeTotals(ev)
  const dev = ev.wcagDeviations
  const gaps = dev.surfaces.filter(s => s.state === 'gap')
  const met = dev.surfaces.filter(s => s.state === 'met')
  const scCount = new Map<string, number>()
  for (const c of ev.quality.components) {
    for (const id of c.wcag) scCount.set(id, (scCount.get(id) ?? 0) + 1)
  }

  const kbd = t.byKind.get('keyboard-spec')
  const axe = t.byKind.get('axe')
  const patternless = ev.quality.components.filter(c => apgLink(c.pattern) === undefined)

  const lines: string[] = [
    ...pageHead(ACCESSIBILITY_STATEMENT, '[2, 3]'),
    `# ${ACCESSIBILITY_STATEMENT.title}`,
    '',
    ...ACCESSIBILITY_STATEMENT.blocks.position!,
    '',
    ...ACCESSIBILITY_STATEMENT.blocks.open!,
    '',
    `::: danger SC ${dev.criterion.id} ${dev.criterion.name} (level ${dev.criterion.level}, new in `
    + `WCAG ${dev.criterion.since}) is not met on ${gaps.length} of ${dev.surfaces.length} drag surfaces`,
    `**${cell(dev.conformanceStatement)}**`,
    '',
    `> ${cell(dev.criterion.text)}`,
    '',
    `The gap is on ${gaps.map(s => `\`${s.component}\``).join(', ')}; the audit below names each`,
    'operation. Every one of them is keyboard-operable, and a keyboard path satisfies SC 2.1.1, not',
    'this one: the criterion is about pointer input and requires a single pointer without dragging.',
    '',
    `[Understanding SC ${dev.criterion.id}](${dev.criterion.url})`,
    ':::',
    '',
    '### The audit',
    '',
    `Scope is not a judgement call: every component carrying the \`drags\` trait was audited, and the `
    + `trait names ${dev.surfaces.length}.`,
    '',
    `| Component | Drag operation | Keyboard (SC 2.1.1) | Single pointer, no drag (SC ${dev.criterion.id}) | State |`,
    '| --- | --- | --- | --- | --- |',
    ...gaps.map(auditRow),
    ...met.map(auditRow),
    '',
  ]

  for (const s of met.filter(s => s.caveat !== undefined)) {
    lines.push(
      `::: warning ${s.component} — a configuration caveat`,
      cell(s.caveat),
      ':::',
      '',
    )
  }

  lines.push(
    '### Why it is not fixed here',
    '',
    ...gaps.map(s => `- **${s.component}** — ${cell(s.ownerDecision)}`),
    '',
    `None of them qualifies for the criterion's own exceptions.`,
    '',
    ...[...new Set(gaps.map(s => cell(s.notEssential)))].map(reason => `- ${reason}`),
    '',
    '**The scoped follow-up, as handed to the owner:**',
    '',
    `> ${cell(dev.followUp)}`,
    '',
    `Measured by \`${cell(dev.recordedAt.measuredBy)}\`, recorded in `
    + `\`packages/core/docs/wcag-deviations.json\` at \`${shortCommit(dev.recordedAt.sourceCommit ?? '')}\` `
    + `(${cell(dev.recordedAt.admissibility)}).`,
    '',
    ...ACCESSIBILITY_STATEMENT.blocks.at!,
    '',
    `Measured: **${t.atExecuted} of ${t.atCells} cells**, over ${t.atComponents} components and `
    + `${t.atPairs} pairings. [The AT matrix](/evidence/at-matrix) lists every one.`,
    '',
    ...ACCESSIBILITY_STATEMENT.blocks.cellDefect!,
    '',
    ...ACCESSIBILITY_STATEMENT.blocks.keyboard!,
    '',
    kbd === undefined
      ? '_No `keyboard-spec` cell exists in the matrix._'
      : `Measured today: of the ${Object.values(kbd.states).reduce((a, b) => a + b, 0)} components that `
        + `owe a \`keyboard-spec\`, ${kbd.states.present ?? 0} have a specification asserting at least one `
        + `key sequence, ${kbd.states.unrun ?? 0} do not, and ${kbd.states.excepted ?? 0} are excepted. `
        + 'None of that is a table of bindings, and the repository has nowhere to hold one.',
    '',
    ...ACCESSIBILITY_STATEMENT.blocks.scope!,
    '',
    '### The criteria, and how many components each applies to',
    '',
    `The published dictionary carries ${ev.quality.wcag.length} success criteria — the ones a component `
    + 'library can actually fail. A criterion applying to no component means nothing in the catalogue '
    + 'declares the behaviour it governs.',
    '',
    '| SC | Criterion | Level | New in | Components in scope |',
    '| --- | --- | --- | --- | --- |',
    ...ev.quality.wcag.map(
      c => `| [${c.id}](${wcagUnderstandingUrl(c.name)}) | ${cell(c.name)} | ${c.level} | WCAG ${c.since} `
        + `| ${scCount.get(c.id) ?? 0} of ${ev.quality.components.length} |`,
    ),
    '',
    '### The automated lane',
    '',
    axe === undefined
      ? '_No automated accessibility cell exists in the matrix._'
      : `An automated accessibility assertion is bound to ${axe.states.present ?? 0} of `
        + `${Object.values(axe.states).reduce((a, b) => a + b, 0)} components; `
        + `${axe.states.unrun ?? 0} have none. Automated checking finds a minority of accessibility `
        + 'defects even where it passes, so this is published as coverage, never as conformance.',
    '',
    '### Components with no APG pattern',
    '',
    patternless.length === 0
      ? 'Every component maps to a WAI-ARIA Authoring Practices pattern.'
      : `${patternless.length} of ${ev.quality.components.length} components map to no APG pattern — `
        + `they are declared \`custom\` or \`none\`, and a declaration of \`custom\` is required to carry `
        + 'a written reason, which their pages print. There is no keyboard contract to link for them, '
        + 'and their pages say so rather than linking a pattern that does not describe them.',
    '',
    ...provenance(ev, [
      'packages/core/docs/quality-matrix.json',
      'packages/core/docs/capability-matrix.json',
      'packages/core/docs/wcag-deviations.json',
      'e2e/at-matrix/index.json',
    ]),
  )
  return `${escapeForVue(lines).join('\n').trimEnd()}\n`
}

