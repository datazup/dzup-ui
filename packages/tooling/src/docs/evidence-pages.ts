/** `/evidence/styling-posture` — the statement, with its counts generated. */
export function renderStylingPosturePage(
  ev: EvidenceSources,
  artifact: ComponentMetaArtifact,
): string {
  const declaring = ev.capability.rows.filter(r => r.anatomy === 'declared').map(r => r.component)
  const uiPublic = artifact.components
    .filter(c => c.kind === 'public-component' && c.props.some(p => p.name === 'ui'))
    .map(c => c.name)
  const uiParts = artifact.components
    .filter(c => c.kind === 'compound-part' && c.props.some(p => p.name === 'ui'))
    .map(c => c.name)
  const total = ev.capability.rows.length

  const lines: string[] = [
    ...pageHead(STYLING_POSTURE, '[2, 3]'),
    `# ${STYLING_POSTURE.title}`,
    '',
    ...STYLING_POSTURE.blocks.position!,
    '',
    ...STYLING_POSTURE.blocks.whyCorrected!,
    '',
    ...STYLING_POSTURE.blocks.contract!,
    '',
    '| Layer | What it is | What is measured today |',
    '| --- | --- | --- |',
    '| Design tokens | `--dz-*` custom properties generated from the TypeScript token maps in `@dzup-ui/tokens`. The interchange surface. | Exported as a Design Tokens Community Group document and round-trip verified against the emitted stylesheet in both cascades. |',
    '| Component tokens | `--dz-{component}-{property}`, resolving to the global tokens. Re-map one and every instance follows. | Every CSS value in the library goes through `var(--dz-*)`; raw colour literals fail the token validator. |',
    '| Typed recipes | Styling written with `tv()` in a `.variants.ts` file beside each component. | No `<style scoped>` and no hard-coded colour anywhere in the library. |',
    `| Stable \`data-part\` / \`data-state\` | Selectable from your own stylesheet, on components that have declared an anatomy. | **${declaring.length} of ${total}** components have declared one: ${declaring.map(c => `\`${c}\``).join(', ')}. |`,
    `| The typed \`ui\` prop | A per-instance override keyed by part name, so one instance can be restyled without a selector war. | **${uiPublic.length} of ${total}** public components declare it: ${uiPublic.map(c => `\`${c}\``).join(', ')}${uiParts.length === 0 ? '' : `, plus the compound part${uiParts.length === 1 ? '' : 's'} ${uiParts.map(c => `\`${c}\``).join(', ')}`}. |`,
    '',
    '::: warning The last two rows are a rollout, and the numbers say so',
    `A component that has not declared an anatomy has **not declared** its parts. That is not the same`,
    `claim as having none, and this site never collapses the two: ${total - declaring.length} component `
    + 'pages print nothing under parts because nothing generated says what their parts are, not because',
    'they have none.',
    ':::',
    '',
    ...STYLING_POSTURE.blocks.cascade!,
    '',
    ev.cascadeLayers.length === 0
      ? '_The layer statement could not be read from the library stylesheet, so the layer names are not shown._'
      : `The layers, in the order the library declares them: `
        + `${ev.cascadeLayers.map(l => `\`${l}\``).join(', ')}. Read from the single \`@layer\` statement in `
        + '`packages/core/src/styles/base.css`; nothing on this page names a layer that stylesheet does not.',
    '',
    ...STYLING_POSTURE.blocks.notClaimed!,
    '',
    '## Where to go next',
    '',
    '- [The styling contract](/guide/styling-contract) — how to actually restyle a component.',
    '- [Design tokens](/guide/tokens) — the token tiers and how to re-map them.',
    '- A component page prints an **Anatomy parts (ADR-19)** line when the component has declared one,',
    '  and prints nothing when it has not.',
    '',
    ...provenance(ev, [
      'packages/core/docs/capability-matrix.json',
      'packages/core/src/styles/base.css',
    ]),
  ]
  return `${escapeForVue(lines).join('\n').trimEnd()}\n`
}
