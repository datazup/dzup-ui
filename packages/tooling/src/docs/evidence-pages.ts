/** `/evidence/capability-matrix` — the whole matrix, browsable. */
export function renderCapabilityMatrixPage(ev: EvidenceSources): string {
  const t = computeTotals(ev)
  const order = ['pass', 'present', 'stale', 'excepted', 'unrun']
  const tiers = Object.keys(ev.capability.totals).sort()

  const lines: string[] = [
    ...pageHead({
      title: 'Capability matrix',
      description:
        'Every evidence cell for every public dzup-ui component, by kind and by component, with unrun and stale cells named.',
    }, '[2, 2]'),
    '# Capability matrix',
    '',
    `What each public component owes, and what has been measured. **${t.cells} cells** over `
    + `**${t.components} components**, generated from the quality tiers, the component traits and the `
    + 'declared security boundaries — never assigned by hand.',
    '',
    '::: info Cells are named, not counted',
    'Where a kind is `unrun` or `stale` this page lists **which components**. A count on its own tells',
    'a reader that something is missing without telling them what, which is the shape of evidence that',
    'stops being read.',
    ':::',
    '',
    '## Where the measurements come from',
    '',
    'The matrix is a join, and a missing input silently turns cells into `unrun` rather than failing.',
    'So the inputs are published with it.',
    '',
    '| Input | Path | Available |',
    '| --- | --- | --- |',
    ...Object.entries(ev.capability.inputs).map(
      ([key, v]) => `| \`${key}\` | \`${v.path}\` | ${v.available ? 'yes' : '**no**'} |`,
    ),
    '',
  ]

  const noted = Object.entries(ev.capability.inputs).filter(([, v]) => v.note !== undefined)
  if (noted.length > 0) {
    lines.push('The inputs that carry a recorded caveat:', '')
    for (const [key, v] of noted)
      lines.push(`- **\`${key}\`** — ${cell(v.note)}`)
    lines.push('')
  }

  lines.push(
    '## By risk tier',
    '',
    `| Tier | ${order.join(' | ')} |`,
    `| --- | ${order.map(() => '---').join(' | ')} |`,
    ...tiers.map((tier) => {
      const row = ev.capability.totals[tier] ?? {}
      return `| \`${tier}\` | ${order.map(s => row[s] ?? 0).join(' | ')} |`
    }),
    '',
    '## By kind of evidence',
    '',
    'Each kind, what puts it on a component, and how the cells resolved.',
    '',
    `| Evidence | Required by | Rows | ${order.join(' | ')} |`,
    `| --- | --- | --- | ${order.map(() => '---').join(' | ')} |`,
  )
  for (const [kind, entry] of t.byKind) {
    const rows = Object.values(entry.states).reduce((a, b) => a + b, 0)
    lines.push(
      `| \`${kind}\` | ${cell(entry.origin)} | ${rows} | `
      + `${order.map(s => entry.states[s] ?? 0).join(' | ')} |`,
    )
  }
  lines.push('')

  const withGaps = [...t.byKind.entries()].filter(([, e]) => e.unrun.length > 0 || e.stale.length > 0)
  lines.push(
    `## The ${withGaps.length} kinds with an unmeasured or stale cell, named`,
    '',
  )
  for (const [kind, entry] of withGaps) {
    lines.push(`::: details \`${kind}\` — ${entry.unrun.length} unrun, ${entry.stale.length} stale`)
    if (entry.unrun.length > 0)
      lines.push(`**unrun (${entry.unrun.length}):** ${entry.unrun.map(c => `\`${c}\``).join(', ')}`, '')
    if (entry.stale.length > 0)
      lines.push(`**stale (${entry.stale.length}):** ${entry.stale.map(c => `\`${c}\``).join(', ')}`, '')
    lines.push(':::', '')
  }

  lines.push(
    '## Every component',
    '',
    `All ${t.components} rows. Follow a component to see its cells with their artifacts and notes.`,
    '',
    '| Component | Family | Tier | APG pattern | Boundary | Cells | Unrun | Stale |',
    '| --- | --- | --- | --- | --- | --- | --- | --- |',
  )
  for (const row of [...ev.capability.rows].sort((a, b) => a.component.localeCompare(b.component, 'en'))) {
    const unrun = row.cells.filter(c => c.state === 'unrun').map(c => c.kind)
    const stale = row.cells.filter(c => c.state === 'stale').map(c => c.kind)
    const link = apgLink(row.pattern)
    lines.push(
      `| [${row.component}](/components/${row.component}#accessibility-and-evidence) `
      + `| ${cell(row.family)} | \`${row.tier}\` `
      + `| ${link === undefined ? `\`${row.pattern}\`` : `[\`${row.pattern}\`](${link})`} `
      + `| \`${row.securityBoundary}\` | ${row.cells.length} `
      + `| ${unrun.length === 0 ? '—' : `**${unrun.map(k => `\`${k}\``).join(', ')}**`} `
      + `| ${stale.length === 0 ? '—' : stale.map(k => `\`${k}\``).join(', ')} |`,
    )
  }
  lines.push('')

  lines.push(...provenance(ev, [
    'packages/core/docs/capability-matrix.json',
    'packages/core/docs/quality-matrix.json',
  ]))
  return `${escapeForVue(lines).join('\n').trimEnd()}\n`
}

