/** `/evidence/browser-support` — the statement, wrapped around the engine lane. */
export function renderBrowserSupportPage(ev: EvidenceSources): string {
  const engines = ev.engines
  const lines: string[] = [
    ...pageHead(BROWSER_SUPPORT, '[2, 3]'),
    `# ${BROWSER_SUPPORT.title}`,
    '',
    ...BROWSER_SUPPORT.blocks.position!,
    '',
    ...BROWSER_SUPPORT.blocks.whatRuns!,
    '',
  ]

  if (engines === undefined) {
    lines.push(
      '::: danger No engine-lane record exists in this checkout',
      '`e2e/matrix/engine-ratchets.json` is absent, so **no engine numbers are shown on this page**.',
      'Nothing here should be read as browser evidence. The lane exists and can be run; its record is',
      'not present, and rendering the page around the absence is the only honest option — a browser',
      'lane whose record has gone missing is exactly how an evidence surface starts overstating itself.',
      ':::',
      '',
    )
  }
  else {
    const names = Object.keys(engines.engines)
    const conditions = [...new Set(names.flatMap(n => engines.engines[n]!.conditionsRun))]
    lines.push(
      `| Engine | Version | Conditions | Targets | Cells run | Passed | Unexpected failures | Wall clock | Run on |`,
      `| --- | --- | --- | --- | --- | --- | --- | --- | --- |`,
      ...names.map((name) => {
        const e = engines.engines[name]!
        return `| \`${name}\` | ${cell(e.version)} | ${e.conditionsRun.length} `
          + `| ${e.summary.runnableTargets} | ${e.summary.cellsRun} | ${e.summary.passed} `
          + `| ${e.summary.unexpectedFailure} | ${cell(e.summary.wallClock)} | ${cell(e.summary.ranAt)} |`
      }),
      '',
      `Conditions: ${conditions.map(c => `\`${c}\``).join(', ')}. `
      + `Driver: Playwright \`${cell(engines.playwrightVersion)}\` on \`${cell(engines.platform)}\`.`,
      '',
      `**Cross-engine result, measured \`${cell(engines.crossEngineResult.measuredAt)}\`:** `
      + `${cell(engines.crossEngineResult.note)}`,
      '',
      `The cross-engine ledger of expected failures holds `
      + `**${engines.crossEngineResult.ledgerEntries} entries**`
      + `${ev.knownFailures === undefined ? '' : ` (\`e2e/matrix/known-failures.json\`, closed by \`${cell(ev.knownFailures.closedBy?.split('.')[0])}\`)`}. `
      + 'A listed cell still runs and still costs wall-clock; the lane fails if one unexpectedly passes, '
      + 'so the file can only shrink.',
      '',
      `**How far this goes:** ${cell(engines.admissibility)}`,
      '',
      `**Method:** ${cell(engines.method)}`,
      '',
    )
    const declaredUnrun = names
      .map(n => engines.engines[n]!.summary.declaredUnrunTargets)
      .reduce((a, b) => Math.max(a, b), 0)
    if (declaredUnrun > 0) {
      lines.push(
        `::: warning ${declaredUnrun} target${declaredUnrun === 1 ? '' : 's'} in the lane `
        + `${declaredUnrun === 1 ? 'is' : 'are'} declared unrun`,
        'A component with no published story cannot be driven by a story-based lane. It is declared',
        'unrun rather than skipped, so it stays visible in the arithmetic instead of disappearing from',
        'the denominator.',
        ':::',
        '',
      )
    }
  }

  lines.push(
    ...BROWSER_SUPPORT.blocks.webkit!,
    '',
    ...BROWSER_SUPPORT.blocks.history!,
    '',
    ...BROWSER_SUPPORT.blocks.baseline!,
    '',
    ...BROWSER_SUPPORT.blocks.notMeasured!,
    '',
    ...provenance(ev, [
      'e2e/matrix/engine-ratchets.json',
      'e2e/matrix/known-failures.json',
      'packages/core/docs/capability-matrix.json',
    ]),
  )
  return `${escapeForVue(lines).join('\n').trimEnd()}\n`
}

