/**
 * The banner every evidence page carries.
 *
 * Deliberately not `GENERATED_BANNER`: that one names `component-meta.json` and
 * points an editor at `components/_usage/`, neither of which is true here. A
 * banner that misdescribes where its own content comes from is a small lie in
 * the one place on the page whose whole job is provenance.
 */
export const EVIDENCE_BANNER
  = '<!-- GENERATED by `yarn generate:docs-pages` from the evidence artifacts listed under\n'
    + '     Provenance at the foot of this page. The prose is authored in\n'
    + '     packages/tooling/src/docs/statements.ts and contains no metric; every number here is\n'
    + '     read from an artifact at build time. Edits to this file are overwritten. -->'

/** Front matter + banner, shared by every page in this module. */
function pageHead(statement: Pick<StatementProse, 'title' | 'description'>, outline: string): string[] {
  return [
    '---',
    `title: ${yamlString(statement.title)}`,
    `description: ${yamlString(statement.description)}`,
    `outline: ${outline}`,
    '---',
    '',
    EVIDENCE_BANNER,
    '',
  ]
}

/** The provenance footer every evidence page carries. Composed, never typed. */
function provenance(ev: EvidenceSources, paths: readonly string[]): string[] {
  return [
    '## Provenance',
    '',
    'Every number on this page is read from a generated artifact at build time. The artifacts, and the',
    'SHA-256 of the exact bytes these pages were rendered from:',
    '',
    '| Artifact | sha256 | Present |',
    '| --- | --- | --- |',
    ...paths.map((p) => {
      const fp = ev.fingerprints[p]
      return `| \`${p}\` | ${fp === undefined ? '—' : `\`${fp.slice(0, 16)}…\``} | ${fp === undefined ? '**absent in this checkout**' : 'yes'} |`
    }),
    '',
    `Capability matrix \`sourceCommit\` \`${shortCommit(ev.capability.sourceCommit)}\` · quality matrix `
    + `\`${shortCommit(ev.quality.sourceCommit)}\`.`,
    '',
    '::: warning Standing',
    'Locally qualified. Not continuous-integration evidence, not release evidence, not production',
    'evidence. See [what this evidence is admissible for](/evidence/#what-this-evidence-is-admissible-for).',
    ':::',
    '',
  ]
}

